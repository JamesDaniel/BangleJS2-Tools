/**
 * Bangle.js 2 Code Generator
 * Converts visual layout hierarchies into clean, idiomatic Espruino JavaScript code.
 */

class BangleCodeGenerator {
  /**
   * Generates clean JavaScript string from layout object
   */
  static generateLayoutObject(node, indent = 2) {
    const pad = " ".repeat(indent);
    const childPad = " ".repeat(indent + 2);

    if (!node) return "{}";

    const props = [];

    if (node.type !== undefined) {
      props.push(`type: ${JSON.stringify(node.type)}`);
    }

    if (node.id) {
      props.push(`id: ${JSON.stringify(node.id)}`);
    }

    if (node.label !== undefined) {
      props.push(`label: ${JSON.stringify(node.label)}`);
    }

    if (node.font) {
      props.push(`font: ${JSON.stringify(node.font)}`);
    }

    if (node.src) {
      if (typeof node.src === "string" && BangleIcons.get(node.src)) {
        const icon = BangleIcons.get(node.src);
        props.push(`src: ${BangleIcons.toEspruinoImage(icon)}`);
      } else {
        props.push(`src: ${JSON.stringify(node.src)}`);
      }
    }

    if (node.scale && node.scale !== 1) {
      props.push(`scale: ${node.scale}`);
    }

    if (node.col) {
      props.push(`col: ${JSON.stringify(node.col)}`);
    }

    if (node.bgCol) {
      props.push(`bgCol: ${JSON.stringify(node.bgCol)}`);
    }

    if (node.btnFaceCol) {
      props.push(`btnFaceCol: ${JSON.stringify(node.btnFaceCol)}`);
    }

    if (node.btnBorderCol) {
      props.push(`btnBorderCol: ${JSON.stringify(node.btnBorderCol)}`);
    }

    if (node.pad) {
      props.push(`pad: ${node.pad}`);
    }

    if (node.fillx) {
      props.push(`fillx: ${node.fillx}`);
    }

    if (node.filly) {
      props.push(`filly: ${node.filly}`);
    }

    if (node.width) {
      props.push(`width: ${node.width}`);
    }

    if (node.height) {
      props.push(`height: ${node.height}`);
    }

    if (node.halign !== undefined && node.halign !== 0) {
      props.push(`halign: ${node.halign}`);
    }

    if (node.valign !== undefined && node.valign !== 0) {
      props.push(`valign: ${node.valign}`);
    }

    if (node.wrap) {
      props.push(`wrap: true`);
    }

    if (node.r) {
      props.push(`r: ${node.r}`);
    }

    if (node.cb) {
      const cbCode = typeof node.cb === "function" ? node.cb.toString() : String(node.cb);
      props.push(`cb: ${cbCode}`);
    }

    if (node.c && Array.isArray(node.c) && node.c.length > 0) {
      const childrenCode = node.c
        .map((child) => this.generateLayoutObject(child, indent + 4))
        .join(",\n");
      props.push(`c: [\n${childrenCode}\n${childPad}]`);
    }

    return `${pad}{\n${childPad}${props.join(`,\n${childPad}`)}\n${pad}}`;
  }

  /**
   * Generates a complete Espruino watch application script
   */
  static generateAppCode(layout, options = {}, metadata = {}) {
    const layoutStr = this.generateLayoutObject(layout, 2).trim();
    const appName = metadata.name || "BangleApp";
    const appId = (metadata.id || appName.toLowerCase().replace(/[^a-z0-9]/g, "")).slice(0, 15);
    const withWidgets = options.showWidgets !== false;
    const isLazy = options.lazy || false;

    let optionsStr = "";
    const optParts = [];
    if (isLazy) optParts.push("lazy: true");
    if (options.btns && options.btns.length > 0) {
      const btnsJson = JSON.stringify(options.btns, null, 2);
      optParts.push(`btns: ${btnsJson}`);
    }
    if (optParts.length > 0) {
      optionsStr = `, { ${optParts.join(", ")} }`;
    }

    return `// =====================================================================
// ${appName} for Bangle.js 2
// Generated by Bangle.js 2 UI Designer
// =====================================================================

var Layout = require("Layout");

var layout = new Layout(
${layoutStr}${optionsStr}
);

${withWidgets ? "// Load system widgets\nBangle.loadWidgets();\n" : ""}// Clear screen and render layout
g.clear();
${withWidgets ? "Bangle.drawWidgets();\n" : ""}layout.render();

// Enable standard physical button / drag UI handler
Bangle.setUI();
`;
  }

  /**
   * Generates BangleApps metadata files
   */
  static generateMetadata(metadata = {}) {
    const name = metadata.name || "My Bangle App";
    const id = (metadata.id || name.toLowerCase().replace(/[^a-z0-9]/g, "")).slice(0, 15);

    const appInfo = {
      id: id,
      name: name,
      src: `${id}.app.js`,
      icon: "app.png",
      version: metadata.version || "0.01",
      description: metadata.description || "Created with Bangle.js 2 UI Designer",
      type: metadata.type || "app"
    };

    return JSON.stringify(appInfo, null, 2);
  }

  /**
   * Generates Espruino Web IDE pre-filled URL
   */
  static generateWebIdeUrl(code) {
    const encoded = encodeURIComponent(code);
    return `https://espruino.com/ide/?code=${encoded}`;
  }
}

if (typeof globalThis !== "undefined") {
  globalThis.BangleCodeGenerator = BangleCodeGenerator;
}
if (typeof module !== "undefined" && module.exports) {
  module.exports = BangleCodeGenerator;
}
